/**
 * 磁贴面板 —— 对应影视仓设置页的方格布局：
 *
 *   ┌─────────────────────────┬─────────────────────────┐
 *   │ 配置地址             >  │ 线路切换            下 >│
 *   └─────────────────────────┴─────────────────────────┘
 *   ┌────────┬────────┬────────┬────────┐
 *   │首页推荐│首页Tab │搜索展示│缓存时长│  ← 四列矩阵
 *   └────────┴────────┴────────┴────────┘
 *
 * 两行两种栅格：第一行是「大项」，其余是「键值项」。
 */
export interface TileAction {
  key: string
  label: string
  /** 右侧的值，例如「默认」「1天」；纯操作项留空 */
  value?: string
  /** 值后面是否带箭头，默认 true */
  arrow?: boolean
  hint?: string
  disabled?: boolean
  onClick?: () => void
}
